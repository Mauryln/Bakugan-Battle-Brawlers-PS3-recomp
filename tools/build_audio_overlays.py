"""Lift Bakugan's two Multistream kernels at their runtime local-store address.

The game copies the executable segments of these embedded SPU ELFs to 0x32D80.
Their ordinary lifts at 0x80 cannot resolve calls to 0x32D98. All generated code
and bytes stay in the ignored spu/ tree; no game data is distributed.
"""
from pathlib import Path
import argparse
import json
import struct
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "ps3recomp-src/tools"))
from find_spu_functions import detect_functions, parse_elf, pick_text

LOAD_BASE = 0x32D80
KERNELS = [("spu_0003_at_00666C00", "audio_pcm", 6),
           ("spu_0004_at_00668E00", "audio_mix", 7)]


def guest_address(elf: bytes, file_offset: int) -> int:
    """Map an EBOOT file position through its ELF64 program headers."""
    phoff = struct.unpack_from(">Q", elf, 0x20)[0]
    entsize, count = struct.unpack_from(">HH", elf, 0x36)
    for i in range(count):
        pos = phoff + i * entsize
        kind = struct.unpack_from(">I", elf, pos)[0]
        offset, address, _, size = struct.unpack_from(">4Q", elf, pos + 8)
        if kind == 1 and offset <= file_offset < offset + size:
            return address + file_offset - offset
    raise ValueError(f"Unmapped embedded kernel at file offset {file_offset:#x}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    eboot_path = ROOT / "game/PS3_GAME/USRDIR/EBOOT.elf"
    output = ROOT / "bakugan-recomp/spu"
    registry = output / "spu_audio_overlays.c"
    dependencies = [Path(__file__), eboot_path, ROOT / "ps3recomp-src/tools/spu_lifter.py"]
    images = [ROOT / "analysis/spu_eboot" / f"{name}.elf" for name, _, _ in KERNELS]
    dependencies += images
    generated = [registry] + [output / name / "spu_recomp.c" for _, name, _ in KERNELS]
    if not args.force and all(p.exists() for p in generated) and min(
            p.stat().st_mtime for p in generated) >= max(p.stat().st_mtime for p in dependencies):
        print("Multistream overlays already lifted")
        return
    eboot = eboot_path.read_bytes()
    declarations, registrations = [], []
    for (_, name, image_id), path in zip(KERNELS, images):
        elf = path.read_bytes()
        offset, address, size = pick_text(parse_elf(elf)["phs"])
        source_offset = eboot.find(elf)
        if source_offset < 0:
            raise ValueError(f"{path.name} does not match this EBOOT")
        source_ea = guest_address(eboot, source_offset + offset)
        bounds, _ = detect_functions(elf, verbose=False)
        delta = LOAD_BASE - address
        folder = output / name
        folder.mkdir(parents=True, exist_ok=True)
        raw, functions = folder / "text.bin", folder / "functions.json"
        raw.write_bytes(elf[offset:offset + size])
        functions.write_text(json.dumps([
            {"start": hex(start + delta), "end": hex(end + delta)} for start, end in bounds]))
        prefix = f"bakugan_{name}_"
        subprocess.run([sys.executable, str(ROOT / "ps3recomp-src/tools/spu_lifter.py"),
            str(raw), "--base", hex(LOAD_BASE), "--functions", str(functions),
            "--symbol-prefix", prefix, "--merge-chunks", "--return-entries",
            "--extra-funcs", hex(0x98 + delta), "--output", str(folder)], check=True)
        declarations.append(f"extern void {prefix}spu_recomp_register(void);")
        declarations.append(f"static const uint8_t {name}_signature[16] = {{"
                            + ",".join(f"0x{value:02X}" for value in elf[offset:offset + 16]) + "};")
        registrations += [f"    spu_begin_image({image_id}); {prefix}spu_recomp_register();",
                          f"    spu_overlay_register_region(0x{source_ea:08X}u, 0x{size:X}u, {image_id});",
                          f"    spu_overlay_register_sig({name}_signature, {image_id});"]
    registry.write_text("/* GENERATED by tools/build_audio_overlays.py. */\n"
        '#include "spu_context.h"\n'
        "extern void spu_begin_image(int);\n"
        "extern void spu_overlay_register_region(uint32_t, uint32_t, int);\n"
        "extern void spu_overlay_register_sig(const uint8_t[16], int);\n"
        + "\n".join(declarations) + "\n"
        "__attribute__((constructor)) static void bakugan_audio_register(void)\n{\n"
        + "\n".join(registrations) + "\n    spu_begin_image(0);\n}\n",
        encoding="utf-8", newline="\n")
    print(f"Generated {registry}")


if __name__ == "__main__":
    main()
